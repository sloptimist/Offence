INVOICE = (Path(__file__).parent/'fixtures/bolt11-description-hash.txt').read_text().strip()
AMOUNT = {'currency':'BTC','amount':'0.02000000000'}
COMMITMENT = '3925b6f67e2c340036ed12093dd44e0368df1b6ea26c53dbe4811f58fd5db8c1'
RECEIVER = '00000000-0000-4000-8000-000000000001'
INVOICE_ID = '00000000-0000-4000-8000-000000000002'


def test_official_bolt11_vector_and_corruption():
    # Official BOLT11 description-hash example, not generated by this parser.
    # https://github.com/lightning/bolts/blob/master/11-payment-encoding.md
    result=decode_invoice(INVOICE)
    assert result['amount_msat']==2_000_000_000
    assert result['description_hash']==COMMITMENT
    assert result['expires']==1496314658+3600
    assert decode_invoice(INVOICE.upper())==result
    for bad in [INVOICE[:-1]+'q',INVOICE[:100],INVOICE.replace('lnbc','lnbcrt',1),INVOICE[:10].upper()+INVOICE[10:]]:
        with pytest.raises(ValueError): decode_invoice(bad)


